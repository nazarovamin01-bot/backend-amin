# 6-kun: Funksiyalar (def)

# 1. Oddiy funksiya yaratish
def salomlash():
    print("Salom, dunyo!")

# Funksiyani chaqirish (ishga tushirish)

salomlash()

print("---")

# 2. Argument (parametr) qabul qiluvchi funksiya
def shaxsiy_salom(ism):
    print("Salom, " + ism + "!")

shaxsiy_salom("Amin")
shaxsiy_salom("Ali")
